def get_knowledge(agent_id: str, topic: str, **kwargs) -> str:
    """获取指定宗教和主题的知识片段，支持变量替换"""
    agent_knowledge = KNOWLEDGE.get(agent_id, {})
    snippets = agent_knowledge.get(topic, agent_knowledge.get("综合", []))
    if not snippets:
        return ""
    result = "\n".join(f"- {s}" for s in snippets)
    # 支持变量替换（如道家的五行分析）
    for key, value in kwargs.items():
        result = result.replace(f"{{{key}}}", str(value))
    return result
